/**
 * Fit a local reference image inside a model's PUBLISHED pixel ceiling.
 *
 * WHY THIS EXISTS. `providers/image/genstudio.ts` refuses — correctly — to
 * upload a reference whose longest edge exceeds the model's published
 * `reference_image_max_dimension`, and tells the customer to "resize it and
 * retry". That is the right answer for an image the customer chose. It is the
 * WRONG answer for `img2img-references/composition.png`, because Story Studio
 * rendered that file itself, at the model's own published output size.
 *
 * Measured against the live catalogue on 2026-08-27: every one of the ten
 * reference-capable image products publishes
 * `reference_image_max_dimension: 1024`, while the default 1K/16:9 output row
 * is 1280x720. So a composition template generated by this app is ALWAYS wider
 * than the ceiling it would then be submitted against, and attaching it
 * untouched would fail every scene in the batch before the first charged POST.
 * Telling the owner to go and resize an image the app produced for him is not
 * a thing this app is allowed to do.
 *
 * WHAT IT DOES NOT DO. It never enlarges, never converts a file that already
 * fits, and never touches the source. The fitted copy is a derived artefact
 * written beside the original under a dot-directory, so the references folder
 * the customer browses keeps showing exactly the images the customer put there.
 * A model that publishes NO ceiling gets no resize at all — Story Studio does
 * not invent a limit GenStudio never stated (same rule as the provider).
 */

import fs from 'fs/promises'
import path from 'path'
import sharp from 'sharp'
import { assertDecodableImage } from './image-validation.js'

/** Derived, app-owned copies live here — never mixed in with the originals. */
export const FITTED_REFERENCE_DIRNAME = '.render-fit'

export interface FittedReference {
  /** Absolute path to submit. The source itself when no resize was needed. */
  path: string
  /** true when a downscaled copy was written. */
  resized: boolean
  /** Source pixel size, when it could be read. */
  from?: { width: number; height: number }
  /** Submitted pixel size, when a resize happened. */
  to?: { width: number; height: number }
}

/**
 * Return a path that is safe to submit as a reference for a model publishing
 * `maxDimension` pixels on its longest side.
 *
 * @param sourcePath  absolute path to the reference image on disk.
 * @param maxDimension the model's published ceiling, or undefined when it
 *   publishes none — in which case the source is returned untouched.
 * @param cacheDir directory for the derived copy (created on demand).
 */
export async function fitReferenceImage(
  sourcePath: string,
  maxDimension: number | undefined,
  cacheDir: string,
): Promise<FittedReference> {
  if (!Number.isInteger(maxDimension) || !maxDimension || maxDimension <= 0) {
    return { path: sourcePath, resized: false }
  }

  // Read the size through the app's own decode check rather than a bare
  // `metadata()` call. `metadata()` reads headers only, so a truncated PNG
  // passes it and then throws mid-resize with a raw sharp stack; this fully
  // decodes and raises the precise "Reference image is corrupt or incomplete"
  // message the rest of the app uses — and it does so BEFORE any scene is
  // submitted, so a bad reference costs nothing. The result is cached by
  // size+mtime, so the whole batch pays for one decode.
  const { width, height } = await assertDecodableImage(sourcePath, 'Reference image')
  if (Math.max(width, height) <= maxDimension) {
    return { path: sourcePath, resized: false, from: { width, height } }
  }

  await fs.mkdir(cacheDir, { recursive: true })
  const fittedPath = path.join(cacheDir, `${path.parse(sourcePath).name}.png`)
  const output = await sharp(sourcePath, { failOn: 'error' })
    .resize({ width: maxDimension, height: maxDimension, fit: 'inside', withoutEnlargement: true })
    .png()
    .toFile(fittedPath)

  return {
    path: fittedPath,
    resized: true,
    from: { width, height },
    to: { width: output.width, height: output.height },
  }
}

/**
 * The same fit, applied to bytes on their way to disk rather than to a file
 * already stored.
 *
 * WHY A SECOND ENTRY POINT. `fitReferenceImage` above runs at SUBMIT time,
 * where exactly one model is in scope and its published ceiling is known. That
 * is the right place for an app-generated composition template. It is the
 * wrong place for a photo the customer uploaded, because only one of the two
 * generators ever called it: `generators/images.ts` — the Scene and Thumbnail
 * generator, which submits master, per-scene, character, thumbnail and
 * art-style references — never did. A phone photo is around 4000px on its long
 * edge, every reference-capable product publishes a 1024px ceiling, so the
 * upload succeeded and then every render using it failed with "resize it and
 * retry" on an image the customer had no tool to resize.
 *
 * Fitting once at the upload boundary fixes every downstream path at the same
 * time, and costs one decode per upload instead of one per submitted scene.
 *
 * The invented-limit rule still holds: `maxDimension` must be a figure
 * GenStudio published (see `publishedReferenceCeiling`). Pass `undefined` when
 * the catalogue could not be read and the bytes are stored exactly as sent —
 * which is the behaviour this route had before, so an offline upload is never
 * worse off than it was.
 */
export async function fitReferenceBuffer(
  data: Buffer,
  maxDimension: number | undefined,
): Promise<{ data: Buffer; resized: boolean; from?: { width: number; height: number }; to?: { width: number; height: number } }> {
  if (!Number.isInteger(maxDimension) || !maxDimension || maxDimension <= 0) {
    return { data, resized: false }
  }

  let width: number | undefined
  let height: number | undefined
  try {
    const metadata = await sharp(data, { failOn: 'error' }).metadata()
    width = metadata.width
    height = metadata.height
  } catch {
    // Not decodable as an image. Storing it unchanged keeps this route's old
    // behaviour — the byte cap is its only gate — and leaves the real, precise
    // "corrupt or incomplete" message to the decode check at submit time.
    return { data, resized: false }
  }
  if (!width || !height || Math.max(width, height) <= maxDimension) {
    return { data, resized: false, ...(width && height ? { from: { width, height } } : {}) }
  }

  const fitted = await sharp(data, { failOn: 'error' })
    .resize({ width: maxDimension, height: maxDimension, fit: 'inside', withoutEnlargement: true })
    .png()
    .toBuffer({ resolveWithObject: true })

  return {
    data: fitted.data,
    resized: true,
    from: { width, height },
    to: { width: fitted.info.width, height: fitted.info.height },
  }
}
