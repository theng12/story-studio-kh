<template>
  <div class="brush-canvas-wrap">
    <!-- Display layer: source image, fit-to-container. The mask canvas
         is positioned absolutely on top at the same intrinsic size, so
         brush coordinates map 1:1 to the eventual mask PNG dimensions. -->
    <div class="brush-stage" ref="stageEl">
      <img
        v-if="imageUrl"
        :src="imageUrl"
        ref="imgEl"
        class="brush-source-img"
        :alt="alt"
        @load="onImgLoad"
        crossorigin="anonymous"
      />
      <canvas
        ref="canvasEl"
        class="brush-canvas"
        :class="{ 'mode-erase': mode === 'erase' }"
        @mousedown="onPointerDown"
        @mousemove="onPointerMove"
        @mouseup="onPointerUp"
        @mouseleave="onPointerUp"
        @touchstart.prevent="onTouchStart"
        @touchmove.prevent="onTouchMove"
        @touchend.prevent="onPointerUp"
      ></canvas>
      <div v-if="!imgReady" class="brush-loading">
        <LoadingSpinner size="sm" />
        <span class="brush-loading-text">Loading image…</span>
      </div>
    </div>

    <!-- Toolbar: mode, brush size, clear, mask-status. Sits below the
         stage so the user's hand doesn't cover it while painting. -->
    <div class="brush-toolbar">
      <div class="brush-mode-group" role="group" aria-label="Brush mode">
        <button
          type="button"
          :class="['brush-mode-btn', { active: mode === 'paint' }]"
          :title="'Paint mask — areas you paint over will be erased / regenerated by the AI'"
          @click="mode = 'paint'"
        >
          🖌 Paint
        </button>
        <button
          type="button"
          :class="['brush-mode-btn', { active: mode === 'erase' }]"
          :title="'Erase mask — undo a stroke without clearing everything'"
          @click="mode = 'erase'"
        >
          🩹 Erase
        </button>
      </div>

      <label class="brush-size-row" :title="`Brush diameter: ${brushSize}px`">
        Size
        <input
          type="range"
          min="6"
          max="120"
          step="1"
          v-model.number="brushSize"
          class="brush-size-input"
        />
        <span class="brush-size-display">{{ brushSize }}px</span>
      </label>

      <button
        type="button"
        class="btn btn-sm btn-ghost"
        :disabled="!hasMask"
        @click="clearMask"
        title="Clear the entire mask and start over"
      >
        Clear
      </button>

      <span class="brush-status" :class="{ 'has-mask': hasMask }">
        <template v-if="hasMask">
          Mask ready — paint over what you want erased.
        </template>
        <template v-else>
          Paint over the area to erase. Empty mask = no edit applied.
        </template>
      </span>
    </div>
  </div>
</template>

<script setup lang="ts">
/**
 * Mask-painting canvas for the AI image-editor's brush mode.
 *
 * Shows the source image fit-to-container; an overlay <canvas> at the
 * same DPR-adjusted dimensions captures pointer events to draw a binary
 * mask. White pixels = "edit this area"; transparent = "leave alone".
 *
 * On request the canvas is exported as a PNG matching the source image's
 * intrinsic dimensions — that's the contract every inpainting provider
 * we wire (fal.ai LaMa, OpenAI gpt-image-1, kie.ai mask-capable models)
 * shares: image + same-size mask.
 *
 * The mask layer is purely client-side; the parent component requests
 * `getMaskBase64()` only when the user hits Generate.
 */

interface Props {
  imageUrl: string
  alt?: string
}
const props = withDefaults(defineProps<Props>(), { alt: 'Source image' })

const emit = defineEmits<{
  /** Fires whenever the mask transitions from "empty" to "non-empty"
   *  or vice-versa. Parent uses this to enable/disable the Generate
   *  button when in mask mode. */
  'update:hasMask': [hasMask: boolean]
}>()

const stageEl = ref<HTMLDivElement | null>(null)
const imgEl   = ref<HTMLImageElement | null>(null)
const canvasEl = ref<HTMLCanvasElement | null>(null)

const imgReady = ref(false)
const mode = ref<'paint' | 'erase'>('paint')
const brushSize = ref(36)
const hasMask = ref(false)

// Mouse / touch state. We store positions in CANVAS pixel coords (which
// match the source image's intrinsic size after onImgLoad sets the
// canvas resolution). Display vs canvas coords differ by a scale factor
// computed at draw time from the rendered <img> bounding rect.
let drawing = false
let lastX = 0
let lastY = 0

function onImgLoad() {
  const img = imgEl.value
  const cv  = canvasEl.value
  if (!img || !cv) return
  // Match the canvas's bitmap resolution to the source image so the
  // exported mask is pixel-accurate. The CSS `width: 100%` on the canvas
  // takes care of visual scaling.
  cv.width  = img.naturalWidth
  cv.height = img.naturalHeight
  const ctx = cv.getContext('2d')
  if (ctx) {
    ctx.clearRect(0, 0, cv.width, cv.height)
    // White strokes for the mask region, soft-edged for cleaner inpaint
    // results. Inpainting models tolerate (and often prefer) a slight
    // feather over a hard binary edge.
    ctx.lineCap = 'round'
    ctx.lineJoin = 'round'
    ctx.fillStyle = 'rgba(255, 255, 255, 0.85)'
    ctx.strokeStyle = 'rgba(255, 255, 255, 0.85)'
  }
  hasMask.value = false
  emit('update:hasMask', false)
  imgReady.value = true
}

function getCtx(): CanvasRenderingContext2D | null {
  return canvasEl.value?.getContext('2d') || null
}

/**
 * Translate a viewport mouse / touch coordinate into the canvas's
 * intrinsic (pixel) coordinate space, accounting for the CSS scale-down
 * applied by `width: 100%`. Without this, painting on a 1920×1080
 * displayed-as-640×360 image would put strokes at 1/3 the intended
 * coordinates.
 */
function toCanvasCoords(clientX: number, clientY: number): { x: number; y: number } | null {
  const cv = canvasEl.value
  if (!cv) return null
  const rect = cv.getBoundingClientRect()
  const scaleX = cv.width  / rect.width
  const scaleY = cv.height / rect.height
  return {
    x: (clientX - rect.left) * scaleX,
    y: (clientY - rect.top)  * scaleY,
  }
}

function onPointerDown(e: MouseEvent) {
  const pt = toCanvasCoords(e.clientX, e.clientY)
  if (!pt) return
  drawing = true
  lastX = pt.x
  lastY = pt.y
  drawDot(pt.x, pt.y)
}
function onPointerMove(e: MouseEvent) {
  if (!drawing) return
  const pt = toCanvasCoords(e.clientX, e.clientY)
  if (!pt) return
  drawSegment(lastX, lastY, pt.x, pt.y)
  lastX = pt.x
  lastY = pt.y
}
function onPointerUp() {
  drawing = false
}
function onTouchStart(e: TouchEvent) {
  const t = e.touches[0]
  if (!t) return
  onPointerDown({ clientX: t.clientX, clientY: t.clientY } as any)
}
function onTouchMove(e: TouchEvent) {
  const t = e.touches[0]
  if (!t) return
  onPointerMove({ clientX: t.clientX, clientY: t.clientY } as any)
}

function drawDot(x: number, y: number) {
  const ctx = getCtx()
  if (!ctx) return
  if (mode.value === 'erase') {
    ctx.save()
    ctx.globalCompositeOperation = 'destination-out'
    ctx.beginPath()
    ctx.arc(x, y, brushSize.value / 2, 0, Math.PI * 2)
    ctx.fill()
    ctx.restore()
  } else {
    ctx.beginPath()
    ctx.arc(x, y, brushSize.value / 2, 0, Math.PI * 2)
    ctx.fill()
  }
  updateMaskFlag()
}

function drawSegment(x0: number, y0: number, x1: number, y1: number) {
  const ctx = getCtx()
  if (!ctx) return
  if (mode.value === 'erase') {
    ctx.save()
    ctx.globalCompositeOperation = 'destination-out'
    ctx.lineWidth = brushSize.value
    ctx.beginPath()
    ctx.moveTo(x0, y0)
    ctx.lineTo(x1, y1)
    ctx.stroke()
    ctx.restore()
  } else {
    ctx.lineWidth = brushSize.value
    ctx.beginPath()
    ctx.moveTo(x0, y0)
    ctx.lineTo(x1, y1)
    ctx.stroke()
  }
  updateMaskFlag()
}

/**
 * Cheap "is there any non-transparent pixel?" check for toggling the
 * `hasMask` flag. Sampling at a 16-pixel stride keeps it ~O(image/256),
 * which is fine even for 4K images on every stroke.
 */
function updateMaskFlag() {
  const ctx = getCtx()
  const cv  = canvasEl.value
  if (!ctx || !cv) return
  const data = ctx.getImageData(0, 0, cv.width, cv.height).data
  let nonEmpty = false
  for (let i = 3; i < data.length; i += 4 * 16) {
    if (data[i] > 0) { nonEmpty = true; break }
  }
  if (nonEmpty !== hasMask.value) {
    hasMask.value = nonEmpty
    emit('update:hasMask', nonEmpty)
  }
}

function clearMask() {
  const ctx = getCtx()
  const cv  = canvasEl.value
  if (!ctx || !cv) return
  ctx.clearRect(0, 0, cv.width, cv.height)
  hasMask.value = false
  emit('update:hasMask', false)
}

/**
 * Export the painted mask as a base64-encoded PNG. The image is binary
 * (white where painted, transparent elsewhere) to match what fal.ai LaMa,
 * OpenAI gpt-image-1, and the kie.ai mask-capable endpoints all expect.
 *
 * Returns `null` when the mask is empty so the caller can fall back to
 * the prompt-only edit path.
 */
function getMaskBase64(): string | null {
  if (!hasMask.value) return null
  const cv = canvasEl.value
  if (!cv) return null
  // toDataURL returns a `data:image/png;base64,...` URL. Most provider
  // APIs accept the bare base64 portion, but a couple want the full
  // data URL — caller decides which to slice off.
  return cv.toDataURL('image/png')
}

defineExpose({ getMaskBase64, clearMask })
</script>

