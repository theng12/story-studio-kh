/**
 * Bulk "Compact / Fill Gaps" — shift existing accepted episodes BACKWARD
 * to fill the gaps left by removed ideas. Inverse direction of
 * `adoptBulkRenumber` (which shifts FORWARD to make room for orphans).
 *
 * Use case: user had episodes TN0001..TN0010, deleted TN0001..TN0007 from
 * the Ideas tab (older content taken down from YouTube), and wants the
 * remaining TN0008..TN0010 to slide down to TN0001..TN0003 so the
 * numbering starts at 1 again.
 *
 * Reuses the v1.0.38 `.renumber-undo.json` infrastructure — the file
 * format already covers this case (rename_plan is the only field that
 * matters; `adopted` is empty for compact since we're not pulling in
 * any new orphans). The Revert banner on the Unlinked Uploads tab
 * surfaces unchanged, and `revertRenumber` runs the inverse plan with
 * no special-casing.
 *
 * Sequence (mirrors adoptBulkRenumber but with sort flipped):
 *   Stage 0 — write `.renumber-undo.json`
 *   Stage 1 — rename folders, ASCENDING by new code (smallest target
 *             first so it lands in a vacated low-numbered slot before
 *             any potential downstream collision)
 *   Stage 2 — atomic ideas.json patch via im.applyRenumberPatch
 *   Stage 3 — reset next_episode_number to N+1; recycled_numbers clears
 *             via the auto-heal pass inside applyRenumberPatch
 *
 * Orphan-folder collisions (a leftover TN0001 folder from a deleted
 * idea is blocking the slot) surface as Stage-1 rename errors and are
 * reported in the result. The undo plan is already on disk by then so
 * the user can revert; the partial state is safe.
 */

import fs from 'fs/promises'
import path from 'path'
import { existsSync } from 'fs'
import * as pm from './project-manager.js'
import * as im from './idea-manager.js'
import { resolveEpisodePaths, formatEpisodeCode, episodeNumber } from './utils.js'
import {
  writeUndoSidecar, type RenumberUndoSidecar,
} from './upload-renumber-undo.js'

export interface CompactRename {
  old_code: string
  new_code: string
  title: string
}

export interface CompactPreview {
  /** Renames the operation will perform (no-ops excluded). */
  rename_plan: CompactRename[]
  /** Episodes already at the correct position (no rename needed). */
  noop_count: number
  /** Total accepted episodes — `rename_plan.length + noop_count`. */
  total_accepted: number
  /** next_episode_number before compact. Captured for rollback. */
  current_next_episode_number: number
  /**
   * next_episode_number AFTER compact lands successfully — equals
   * `total_accepted + 1`, so the next Accept hands out the slot
   * immediately following the last compacted episode.
   */
  target_next_episode_number: number
}

export interface CompactResult extends CompactPreview {
  /** Renames that fs-renamed cleanly. */
  renamed: Array<{ old_code: string; new_code: string; old_dir: string; new_dir: string }>
  /** Renames that failed mid-stage — the user has the undo sidecar to revert. */
  errors: Array<{ stage: string; detail: string }>
}

/**
 * Compute the compact plan without touching disk or ideas.json. The UI
 * uses this to populate the preview modal; running compact afterwards
 * with the same accepted-idea snapshot produces identical renames.
 *
 * The plan is generated by sorting accepted ideas by their CURRENT
 * episode number and reassigning target codes 1..N in that order. This
 * preserves the user's existing chronological / curated ordering — we
 * just close the gaps.
 */
export async function previewCompact(slug: string): Promise<CompactPreview> {
  const meta = await pm.getProject(slug)
  if (!meta) throw new Error('Project not found')

  const ideas = await im.getIdeas(slug, 'accepted')
  const sorted = ideas
    .filter(i => !!i.episode_code)
    .sort((a, b) => {
      try {
        return episodeNumber(a.episode_code!, meta.episode_prefix)
             - episodeNumber(b.episode_code!, meta.episode_prefix)
      } catch {
        return (a.episode_code || '').localeCompare(b.episode_code || '', undefined, { numeric: true })
      }
    })

  const rename_plan: CompactRename[] = []
  let noop_count = 0
  for (let i = 0; i < sorted.length; i++) {
    const idea = sorted[i]!
    const targetNum = i + 1
    const targetCode = formatEpisodeCode(targetNum, meta.episode_prefix, meta.episode_digits)
    if (idea.episode_code === targetCode) {
      noop_count++
      continue
    }
    rename_plan.push({
      old_code: idea.episode_code!,
      new_code: targetCode,
      title: idea.title || idea.episode_code!,
    })
  }

  const current_next_episode_number = await im.getNextEpisodeNumber(slug)

  return {
    rename_plan,
    noop_count,
    total_accepted: sorted.length,
    current_next_episode_number,
    target_next_episode_number: sorted.length + 1,
  }
}

/**
 * Run the compact for real. Stage 0 writes the undo sidecar before any
 * destructive work, so a Stage-1 / Stage-2 failure is recoverable via
 * the existing Revert banner.
 *
 * Returns the same shape as `previewCompact` plus per-stage outcome
 * arrays so the UI can show "X folders renamed, Y errors — see logs".
 */
export async function compactAcceptedEpisodes(slug: string): Promise<CompactResult> {
  const meta = await pm.getProject(slug)
  if (!meta) throw new Error('Project not found')

  const preview = await previewCompact(slug)
  const renamed: CompactResult['renamed'] = []
  const errors: CompactResult['errors'] = []

  if (preview.rename_plan.length === 0) {
    // No-op compact (everything already at lowest slots). Don't write an
    // undo sidecar for a no-op — that would leave a misleading "you can
    // revert this" banner on the Unlinked Uploads tab when nothing
    // happened.
    return { ...preview, renamed, errors }
  }

  // Stage 0: write undo sidecar before any disk renames or ideas.json
  // patches. Reuses the v1.0.38 schema; `adopted: []` because no orphan
  // adoption is happening here. revertRenumber handles the empty
  // adopted array correctly (Stage A is a no-op when there's nothing
  // to remove).
  const undoPlan: RenumberUndoSidecar = {
    schema_version: 1,
    performed_at: new Date().toISOString(),
    rename_plan: preview.rename_plan.map(r => ({ old_code: r.old_code, new_code: r.new_code })),
    adopted: [],
    previous_next_episode_number: preview.current_next_episode_number,
    episode_prefix: meta.episode_prefix,
    episode_digits: meta.episode_digits,
  }
  try {
    await writeUndoSidecar(slug, undoPlan)
  } catch (e: any) {
    errors.push({ stage: 'write undo sidecar', detail: e?.message || 'undo write failed' })
    // Hard-fail: the locked acceptance for compact promises a rollback
    // path. Without the sidecar the user has no way back, so refuse to
    // proceed.
    return { ...preview, renamed, errors }
  }

  // Stage 1 (fs only): rename folders ASCENDING by new number. For a
  // down-shift, smallest target first — TN0008 → TN0001 lands first
  // (the TN0001 slot is already empty post-deletion), then TN0009 →
  // TN0002, and so on. No collision risk because every target number
  // is below every source number for that pair.
  //
  // If a target slot is occupied by an orphan folder (a leftover from
  // a previously-deleted idea — see the safeguard work in this same
  // version), fs.rename throws ENOTEMPTY / EISDIR. We collect that as
  // an error and keep going for the rest; the undo sidecar is already
  // on disk so the user can revert the partial state.
  const sortedByNew = preview.rename_plan.slice().sort((a, b) => {
    return episodeNumber(a.new_code, meta.episode_prefix)
         - episodeNumber(b.new_code, meta.episode_prefix)
  })
  const ideas = await im.getIdeas(slug, 'accepted')
  const ideaIdByOldCode = new Map<string, string>()
  for (const i of ideas) {
    if (i.episode_code) ideaIdByOldCode.set(i.episode_code, i.id)
  }

  const renamePatch: Array<{ idea_id: string; new_code: string }> = []
  for (const r of sortedByNew) {
    const ideaId = ideaIdByOldCode.get(r.old_code)
    if (!ideaId) {
      errors.push({ stage: `lookup ${r.old_code}`, detail: 'No accepted idea matches this code (raced with another mutator?)' })
      continue
    }
    try {
      const oldPaths = await resolveEpisodePaths(slug, r.old_code, r.title)
      const newPaths = await resolveEpisodePaths(slug, r.new_code, r.title)
      if (existsSync(oldPaths.episode_dir) && oldPaths.episode_dir !== newPaths.episode_dir) {
        await fs.mkdir(path.dirname(newPaths.episode_dir), { recursive: true })
        try {
          await fs.rename(oldPaths.episode_dir, newPaths.episode_dir)
        } catch (e: any) {
          if (e?.code === 'EXDEV') {
            await copyDirRecursive(oldPaths.episode_dir, newPaths.episode_dir)
            await fs.rm(oldPaths.episode_dir, { recursive: true, force: true })
          } else if (e?.code === 'ENOTEMPTY' || e?.code === 'EEXIST' || e?.code === 'EISDIR') {
            errors.push({
              stage: `rename ${r.old_code} → ${r.new_code}`,
              detail: `Target folder already exists on disk (likely an orphan from a previously-deleted idea). Move or delete it manually, then re-run Compact.`,
            })
            continue
          } else {
            throw e
          }
        }
      }
      // Per-subfolder rename for {code}-scoped names (e.g. "TN0008 - 01 Script").
      await renameCodeScopedSubfolders(newPaths.episode_dir, r.old_code, r.new_code)
      // v1.0.41: rewrite any pinned `selected_thumbnail` filenames in
      // upload_metadata_overrides.json — pinned filenames carry the old
      // code prefix, and the file move alone doesn't update content.
      try {
        const { rewriteSelectedThumbnailOnRename } = await import('./upload-overrides.js')
        await rewriteSelectedThumbnailOnRename(slug, r.new_code, r.title, r.old_code)
      } catch (e: any) {
        errors.push({ stage: `rewrite pin ${r.old_code} → ${r.new_code}`, detail: e?.message || 'pin rewrite failed' })
      }
      // v1.0.43: rename the external root mirror dir + inner files
      // when configured. Non-fatal: external root may be unmounted
      // or unset on this machine — project-tree state is already
      // correct by this point.
      try {
        const { renameExternalEpisodeDir } = await import('./external-video-store.js')
        const ext = await renameExternalEpisodeDir(slug, r.old_code, r.new_code, r.title)
        if (ext.attempted && !ext.renamed && ext.detail) {
          errors.push({ stage: `external rename ${r.old_code} → ${r.new_code}`, detail: ext.detail })
        }
      } catch (e: any) {
        errors.push({ stage: `external rename ${r.old_code} → ${r.new_code}`, detail: e?.message || 'external rename failed' })
      }
      renamed.push({
        old_code: r.old_code,
        new_code: r.new_code,
        old_dir: oldPaths.episode_dir,
        new_dir: newPaths.episode_dir,
      })
      renamePatch.push({ idea_id: ideaId, new_code: r.new_code })
    } catch (e: any) {
      errors.push({ stage: `rename ${r.old_code} → ${r.new_code}`, detail: e?.message || 'rename failed' })
    }
  }

  // Stage 2: commit ideas.json codes for the renames that landed
  // cleanly on disk. applyRenumberPatch runs auto-heal on commit, which
  // walks recycled_numbers and removes any entry whose slot is now in
  // use — important for compact because every freshly-occupied slot
  // (TN0001, TN0002, …) was previously sitting in recycled_numbers
  // from the original idea removals.
  if (renamePatch.length > 0) {
    try {
      await im.applyRenumberPatch(slug, {
        renames: renamePatch,
        advance_next_to: preview.target_next_episode_number,
      })
      // applyRenumberPatch only advances `next_episode_number`; for a
      // compact we typically need to LOWER it (current was N+gaps, new
      // should be N+1). updateNextEpisodeNumber forces the value in
      // either direction.
      await im.updateNextEpisodeNumber(slug, preview.target_next_episode_number)
    } catch (e: any) {
      errors.push({ stage: 'apply rename patch', detail: e?.message || 'patch failed' })
    }
  }

  return { ...preview, renamed, errors }
}

// ── Helpers ──────────────────────────────────────────────────────────────
// Same pattern as upload-orphans.ts / upload-renumber-undo.ts (kept
// inline so this module stands alone — sharing them would mean either
// adding a circular dep or introducing a fourth module just for two
// helpers).

async function copyDirRecursive(src: string, dest: string): Promise<void> {
  await fs.mkdir(dest, { recursive: true })
  const entries = await fs.readdir(src, { withFileTypes: true })
  for (const e of entries) {
    const s = path.join(src, e.name)
    const d = path.join(dest, e.name)
    if (e.isDirectory()) await copyDirRecursive(s, d)
    else if (e.isFile()) await fs.copyFile(s, d)
  }
}

async function renameCodeScopedSubfolders(episodeDir: string, oldCode: string, newCode: string): Promise<void> {
  if (!existsSync(episodeDir)) return
  const entries = await fs.readdir(episodeDir, { withFileTypes: true })
  for (const e of entries) {
    if (!e.isDirectory()) continue
    if (!e.name.includes(oldCode)) continue
    const oldP = path.join(episodeDir, e.name)
    const newName = e.name.replaceAll(oldCode, newCode)
    const newP = path.join(episodeDir, newName)
    try { await fs.rename(oldP, newP) } catch { /* non-fatal */ }
  }
  for (const e of entries) {
    if (!e.isFile()) continue
    if (!e.name.startsWith(oldCode)) continue
    const oldP = path.join(episodeDir, e.name)
    const newName = e.name.replace(oldCode, newCode)
    const newP = path.join(episodeDir, newName)
    try { await fs.rename(oldP, newP) } catch { /* non-fatal */ }
  }
  const updatedEntries = await fs.readdir(episodeDir, { withFileTypes: true })
  for (const e of updatedEntries) {
    if (!e.isDirectory()) continue
    const inner = await fs.readdir(path.join(episodeDir, e.name))
    for (const f of inner) {
      if (!f.startsWith(oldCode)) continue
      const oldP = path.join(episodeDir, e.name, f)
      const newName = f.replace(oldCode, newCode)
      const newP = path.join(episodeDir, e.name, newName)
      try { await fs.rename(oldP, newP) } catch { /* non-fatal */ }
    }
  }
}
