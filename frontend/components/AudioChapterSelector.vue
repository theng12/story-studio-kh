<!--
  AudioChapterSelector — picks which sections (Introduction + chapters)
  audio generation should target. Backed by the per-section status
  endpoint (`/audio-sections`) so users can see at a glance what's already
  on disk, what's missing, and what's currently being generated by a
  running job.

  Replaces the old free-text "Sections" input which forced users to type
  "all" / "intro" / "1,2,3" without knowing what existed for the episode.

  Status pill semantics:
    not_generated → no audio chunks on disk
    partial       → some chunks present, section not whole
    generated     → every chunk present
    generating    → a 'audio' job for this episode is running and the
                    section is in its `sections` param (or the param is
                    missing/all, which targets every section)

  Multi-select: checkboxes plus Select All / None / Missing Only
  bulk actions. The chosen slugs flow back through v-model:selected as
  a comma-joined string ("intro,Chapter_01,Chapter_03") so the existing
  audio backend (which already parses that format) doesn't need a contract
  change.
-->
<template>
  <div class="chapter-selector">
    <div class="cs-header">
      <label class="cs-label">Sections to generate</label>
      <div class="cs-actions">
        <button type="button" class="btn btn-sm btn-ghost" @click="selectAll" :disabled="!sections.length">Select all</button>
        <button type="button" class="btn btn-sm btn-ghost" @click="selectNone" :disabled="!selectedSet.size">Clear</button>
        <button type="button" class="btn btn-sm btn-ghost" @click="selectMissing" :disabled="!hasMissing">Missing only</button>
        <button type="button" class="btn btn-sm btn-ghost" @click="refresh" :disabled="loading" :title="`Re-scan disk`">
          <LoadingSpinner v-if="loading" size="sm" />
          ↻
        </button>
      </div>
    </div>

    <div v-if="!episodeId" class="cs-empty">Select an episode to see its sections.</div>
    <div v-else-if="loading && !sections.length" class="cs-empty">Scanning audio files…</div>
    <div v-else-if="!sections.length" class="cs-empty">
      No sections found. Generate the script first, then this selector will
      list each chapter to target individually.
    </div>

    <ul v-else class="cs-list" role="listbox" aria-multiselectable="true">
      <li
        v-for="s in sections"
        :key="s.slug"
        class="cs-item"
        :class="[`status-${runtimeStatus(s)}`, { selected: selectedSet.has(s.slug) }]"
        :aria-selected="selectedSet.has(s.slug)"
      >
        <label class="cs-row">
          <input
            type="checkbox"
            :checked="selectedSet.has(s.slug)"
            @change="toggle(s.slug, ($event.target as HTMLInputElement).checked)"
            :disabled="!allowDuplicates && runtimeStatus(s) === 'generated'"
            :title="!allowDuplicates && runtimeStatus(s) === 'generated' ? 'Already generated — enable duplicate override below to regenerate' : ''"
          />
          <span class="cs-name">{{ prettyLabel(s.label) }}</span>
          <span
            class="cs-meta"
            title="Narration characters include spaces and reflect the text prepared for TTS."
          >
            {{ formatCount(s.word_count) }} words · {{ formatCount(s.character_count) }} chars ·
            {{ s.present_chunks }}/{{ s.total_chunks }} chunks
          </span>
          <span class="cs-pill" :class="`pill-${runtimeStatus(s)}`">
            {{ statusText(runtimeStatus(s)) }}
          </span>
          <!-- In-app listen: play the generated audio without opening Finder.
               Only shown once at least one chunk exists on disk. -->
          <button
            v-if="s.present_chunks > 0"
            type="button"
            class="cs-play"
            :class="{ playing: playingSlug === s.slug }"
            :title="playingSlug === s.slug ? 'Stop' : 'Play generated audio'"
            :aria-label="playingSlug === s.slug ? 'Stop' : 'Play generated audio'"
            @click.stop.prevent="togglePlay(s)"
          >{{ playingSlug === s.slug ? '⏸' : '▶' }}</button>
          <span v-else class="cs-play-spacer" aria-hidden="true" />
        </label>
      </li>
    </ul>

    <div class="cs-footer">
      <label class="checkbox-label" style="font-size: 12px;">
        <input type="checkbox" v-model="allowDuplicatesLocal" />
        Allow regenerating already-generated sections
      </label>
      <span v-if="effectiveSelected.length" class="text-muted" style="font-size: 11px;">
        Will queue: {{ effectiveSelected.length }} section(s)
        <template v-if="skippedCount"> ({{ skippedCount }} skipped — already generated)</template>
      </span>
    </div>
  </div>
</template>

<script setup lang="ts">
interface SectionRow {
  label: string
  slug: string
  total_chunks: number
  present_chunks: number
  word_count: number
  character_count: number
  status: 'not_generated' | 'partial' | 'generated'
  // Per-chapter refactor: true when the chapter source docx (or intro
  // docx) is newer than every existing audio chunk for this section.
  // Surfaced as a "⚠ stale" pill so the user knows to regenerate audio
  // for it. Audio is NOT auto-deleted.
  audio_stale?: boolean
}

const props = withDefaults(defineProps<{
  projectSlug: string
  episodeId: string
  /** Comma-joined slug list (mirrors the backend contract). */
  selected: string
  /** When false, already-generated sections are excluded from `effective-selected`. */
  allowDuplicates?: boolean
  /** Bump to force a refetch (e.g. after a generation finishes). */
  refreshKey?: number
}>(), { allowDuplicates: false })

const emit = defineEmits<{
  'update:selected': [value: string]
  'update:allowDuplicates': [value: boolean]
  /**
   * Selection AFTER duplicate-skip filtering — what should actually be sent
   * to the backend. Pages that submit jobs read this instead of `selected`.
   */
  'update:effective-selected': [slugs: string[]]
}>()

const { get } = useApi()
const { jobs } = useJobs()
const { error: showError } = useToast()

const sections = ref<SectionRow[]>([])
const loading = ref(false)

// ── In-app playback ─────────────────────────────────────────────────────
// One <audio> at a time, streamed from the new /audio-file endpoint. Lets
// the user listen to a generated section without opening the audio folder.
const playingSlug = ref<string | null>(null)
let audioEl: HTMLAudioElement | null = null

function stopPlay() {
  if (audioEl) { try { audioEl.pause() } catch { /* already stopped */ } audioEl = null }
  playingSlug.value = null
}

function togglePlay(s: SectionRow) {
  if (playingSlug.value === s.slug) { stopPlay(); return }
  stopPlay()
  // Relative /api URL — same origin as the SPA, so cookies (server mode) ride
  // along and seeking works via the endpoint's Range support.
  const url = `/api/projects/${props.projectSlug}/episodes/${encodeURIComponent(props.episodeId)}/audio-file?section=${encodeURIComponent(s.slug)}`
  const el = new Audio(url)
  audioEl = el
  playingSlug.value = s.slug
  el.addEventListener('ended', () => { if (audioEl === el) stopPlay() })
  el.addEventListener('error', () => {
    if (audioEl === el) { stopPlay(); showError("Couldn't play this section's audio.") }
  })
  el.play().catch(() => { if (audioEl === el) stopPlay() })
}

// Stop playback when the episode changes or the component unmounts.
watch(() => props.episodeId, stopPlay)
onBeforeUnmount(stopPlay)
const allowDuplicatesLocal = ref(props.allowDuplicates)

watch(() => props.allowDuplicates, v => { allowDuplicatesLocal.value = v })
watch(allowDuplicatesLocal, v => emit('update:allowDuplicates', v))

const selectedSet = computed(() => new Set(
  props.selected.split(',').map(s => s.trim()).filter(Boolean)
))

function toggle(slug: string, on: boolean) {
  const next = new Set(selectedSet.value)
  if (on) next.add(slug); else next.delete(slug)
  // Preserve the original section order in the emitted string so the
  // backend processes Introduction → Chapter 1 → Chapter 2 in order.
  const ordered = sections.value.map(s => s.slug).filter(s => next.has(s))
  emit('update:selected', ordered.join(','))
}

function selectAll() {
  emit('update:selected', sections.value.map(s => s.slug).join(','))
}
function selectNone() { emit('update:selected', '') }
function selectMissing() {
  const slugs = sections.value
    .filter(s => runtimeStatus(s) !== 'generated')
    .map(s => s.slug)
  emit('update:selected', slugs.join(','))
}

const hasMissing = computed(() =>
  sections.value.some(s => runtimeStatus(s) !== 'generated')
)

// Runtime status overlays the on-disk status with live job state, so a
// section being actively generated by a running job shows as 'generating'
// even though no files exist yet. The 'stale' state is also a runtime
// overlay: a generated section flips to stale when its source script
// docx was rewritten after the audio was last generated.
type RuntimeStatus = 'not_generated' | 'partial' | 'generated' | 'generating' | 'stale'

function runtimeStatus(s: SectionRow): RuntimeStatus {
  const live = jobs.value.find(j =>
    (j.type === 'audio') &&
    j.episode_id === props.episodeId &&
    j.project_slug === props.projectSlug &&
    (j.status === 'running' || j.status === 'queued')
  )
  if (live) {
    const targeted: string = (live.params?.sections as string) || 'all'
    if (targeted === 'all' || targeted.split(',').map(x => x.trim()).includes(s.slug)) {
      return 'generating'
    }
  }
  // Stale only matters for sections that have actually been generated;
  // 'partial' / 'not_generated' already communicate the work-needed
  // state more precisely.
  if (s.status === 'generated' && s.audio_stale) return 'stale'
  return s.status
}

function statusText(status: string): string {
  return status === 'generated' ? '✓ ready'
    : status === 'partial' ? '◐ partial'
    : status === 'generating' ? '⏳ generating'
    : status === 'stale' ? '⚠ stale'
    : '○ pending'
}

function prettyLabel(label: string): string {
  // Section labels come from the docx parser as "Introduction", "Chapter 1",
  // etc. — already display-ready in most cases. Trim defensively.
  return (label || '').trim()
}

function formatCount(value: number): string {
  return Number.isFinite(value) ? value.toLocaleString() : '0'
}

const effectiveSelected = computed(() => {
  const want = sections.value.filter(s => selectedSet.value.has(s.slug))
  if (allowDuplicatesLocal.value) return want.map(s => s.slug)
  return want.filter(s => runtimeStatus(s) !== 'generated').map(s => s.slug)
})
const skippedCount = computed(() =>
  Math.max(0, selectedSet.value.size - effectiveSelected.value.length)
)

watch(effectiveSelected, v => emit('update:effective-selected', v), { immediate: true })

async function refresh() {
  if (!props.episodeId) {
    sections.value = []
    return
  }
  loading.value = true
  try {
    const r = await get<{ sections: SectionRow[] }>(
      `/projects/${props.projectSlug}/episodes/${props.episodeId}/audio-sections`
    )
    sections.value = r.sections || []
    // Sensible default: when the user lands on the page (or switches episode),
    // pre-select every section that needs work. Empty selection = the page
    // will fall back to "all" on submit, but pre-selecting makes the
    // duplicate-prevention behaviour visible — generated rows show up
    // unchecked + disabled instead of looking targeted.
    if (sections.value.length && !props.selected) {
      const missing = sections.value
        .filter(s => s.status !== 'generated')
        .map(s => s.slug)
      if (missing.length) emit('update:selected', missing.join(','))
    }
  } catch {
    sections.value = []
  } finally {
    loading.value = false
  }
}

watch(() => [props.episodeId, props.refreshKey], refresh, { immediate: true })
</script>

