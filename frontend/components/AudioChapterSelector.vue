// Runtime status overlays the on-disk status with live job state, so a
// section being actively generated by a running job shows as 'generating'
// even though no files exist yet. The 'stale' state is also a runtime
// overlay: a generated section flips to stale when its source script
// docx was rewritten after the audio was last generated.
type RuntimeStatus =
  | 'not_generated' | 'partial' | 'generated' | 'stale'
  | 'generating' | 'waiting' | 'queued'

type LiveAttempt = NonNullable<Job['item_progress']>['active'][number]

/** The audio job running for this episode, if there is one. */
const liveJob = computed(() => jobs.value.find(j =>
  j.type === 'audio' &&
  j.episode_id === props.episodeId &&
  j.project_slug === props.projectSlug &&
  (j.status === 'running' || j.status === 'queued'),
))

/**
 * The running job's own account of itself. Absent on a job that has not
 * started staging yet, and on any job from before this shipped — both fall
 * back to the old whole-job overlay below.
 */
const liveProgress = computed(() => liveJob.value?.item_progress || null)

/** Section slug → what that section is doing right now. */
const liveAttempts = computed(() => {
  const map = new Map<string, LiveAttempt>()
  for (const attempt of liveProgress.value?.active || []) {
    if (attempt.key) map.set(attempt.key, attempt)
  }
  return map
})

/**
 * Re-read once a second so a backoff shows a shrinking number rather than a
 * frozen one. A wait that does not visibly tick is a wait users read as a
 * hang, which is the whole thing this display exists to prevent.
 */
const now = ref(Date.now())
let clock: ReturnType<typeof setInterval> | null = null
onMounted(() => { clock = setInterval(() => { now.value = Date.now() }, 1000) })
onBeforeUnmount(() => { if (clock) clearInterval(clock) })

function secondsUntil(iso?: string): number {
  if (!iso) return 0
  return Math.max(0, Math.round((new Date(iso).getTime() - now.value) / 1000))
}

function activeText(a: LiveAttempt): string {
  if (a.state !== 'waiting_retry') return `${prettyLabel(a.label)} — generating`
  const remaining = secondsUntil(a.retry_at)
  if (a.reason === FREE_MAC_WAIT_REASON) {
    return `${prettyLabel(a.label)} — waiting for a free Mac, next try${remaining ? ` in ${remaining}s` : ' now'}`
  }
  return `${prettyLabel(a.label)} — busy, trying again`
    + `${remaining ? ` in ${remaining}s` : ' now'}`
    + ` (attempt ${a.attempt + 1} of ${a.max_attempts})`
}

function runtimeStatus(s: SectionRow): RuntimeStatus {
  const attempt = liveAttempts.value.get(s.slug)
  if (attempt) return attempt.state === 'waiting_retry' ? 'waiting' : 'generating'
  const live = liveJob.value
  if (live) {
    const targeted: string = (live.params?.sections as string) || 'all'
    if (targeted === 'all' || targeted.split(',').map(x => x.trim()).includes(s.slug)) {
      // Sections are fed to the provider in turn, so a targeted row that is
      // not in flight is genuinely still waiting its turn. Only a job that
      // reports nothing (older build, or not yet staged) is painted wholesale
      // as generating, which is what this display used to do to every row.
      if (!liveProgress.value) return 'generating'
      if (s.status !== 'generated') return 'queued'
    }
  }
  // Stale only matters for sections that have actually been generated;
  // 'partial' / 'not_generated' already communicate the work-needed
  // state more precisely.
  if (s.status === 'generated' && s.audio_stale) return 'stale'
  return s.status
}

function statusText(status: string): string {
  return status === 'generated' ? '✓ ready'
    : status === 'partial' ? '◐ partial'
    : status === 'generating' ? '⏳ generating'
    : status === 'waiting' ? '⏸ busy, will retry'
    : status === 'queued' ? '· waiting its turn'
    : status === 'stale' ? '⚠ stale'
    : '○ pending'
}

function inlineActionLabel(section: SectionRow): string {
  return runtimeStatus(section) === 'generated' || runtimeStatus(section) === 'stale'
    ? 'Regenerate'
    : 'Generate'
}

function inlineActionMode(section: SectionRow): SectionAction['mode'] {
  return runtimeStatus(section) === 'generated' || runtimeStatus(section) === 'stale'
    ? 'regenerate'
    : 'generate'
}

/** Every state that means "a running job already owns this section". */
function isLiveStatus(status: RuntimeStatus): boolean {
  return status === 'generating' || status === 'waiting' || status === 'queued'
}

function inlineActionDisabled(section: SectionRow): boolean {
  const status = runtimeStatus(section)
  return isLiveStatus(status) || props.inlineGenerateDisabled
}

function inlineActionTitle(section: SectionRow): string {
  const status = runtimeStatus(section)
  if (status === 'generating') return 'This chapter is already queued or generating.'
  if (props.inlineGenerateDisabled) return props.inlineGenerateDisabledReason || 'Audio generation is not ready.'
  if (status === 'generated' || status === 'stale') {
    return `Regenerate only ${prettyLabel(section.label)} and replace its active audio.`
  }
  return `Narrate only ${prettyLabel(section.label)} with the selected voice.`
}

function prettyLabel(label: string): string {
  // Section labels come from the docx parser as "Introduction", "Chapter 1",
  // etc. — already display-ready in most cases. Trim defensively.
  return (label || '').trim()
}

function formatCount(value: number): string {
  return Number.isFinite(value) ? value.toLocaleString() : '0'
}

const effectiveSelected = computed(() => {
  return sections.value.filter(s => selectedSet.value.has(s.slug)).map(s => s.slug)
})
const missingSections = computed(() => sections.value
  .filter(s => s.status !== 'generated')
  .map(s => s.slug))

watch(effectiveSelected, v => emit('update:effective-selected', v), { immediate: true })
watch(missingSections, v => emit('update:missing-sections', v), { immediate: true })

async function refresh() {
  const revision = ++refreshRevision
  const episodeId = props.episodeId
  const projectSlug = props.projectSlug
  const model = props.model
  const requested = props.requestedSection?.trim()
  if (!episodeId) {
    sections.value = []
    loading.value = false
    loadError.value = ''
    return
  }
  loading.value = true
  loadError.value = ''
  try {
    const r = await get<{ sections: SectionRow[] }>(
      `/projects/${projectSlug}/episodes/${episodeId}/audio-sections`
      + (model ? `?model=${encodeURIComponent(model)}` : '')
    )
    if (revision !== refreshRevision || props.projectSlug !== projectSlug || props.episodeId !== episodeId || props.model !== model || props.requestedSection?.trim() !== requested) return
    sections.value = r.sections || []
    if (requested && sections.value.some(section => section.slug === requested)) {
      unavailableRequestedSection.value = ''
      // A deep link is a deliberate request. It must win over the usual
      // missing-section default so the quoted action stays chapter-scoped.
      emit('update:selected', requested)
      loading.value = false
      await nextTick()
      if (revision !== refreshRevision || props.projectSlug !== projectSlug || props.episodeId !== episodeId || props.model !== model || props.requestedSection?.trim() !== requested) return
      const target = typeof document === 'undefined'
        ? null
        : document.getElementById(`audio-section-${requested}`)
      if (!target) return
      target.scrollIntoView({ behavior: 'smooth', block: 'center' })
      target.focus({ preventScroll: true })
      emit('requested-section-selected', requested)
      return
    }
    if (requested) {
      unavailableRequestedSection.value = requested
      if (props.selected) emit('update:selected', '')
      return
    }
    unavailableRequestedSection.value = ''
    // On landing or episode switch, pre-select each section that needs audio.
    // The page still requires this resolved, non-empty list before submission.
    if (sections.value.length && !props.selected) {
      const missing = sections.value
        .filter(s => s.status !== 'generated')
        .map(s => s.slug)
      if (missing.length) emit('update:selected', missing.join(','))
    }
  } catch (e: any) {
    if (revision === refreshRevision) {
      sections.value = []
      loadError.value = e?.data?.detail || e?.message || 'Could not read this episode’s sections'
    }
  } finally {
    if (revision === refreshRevision) loading.value = false
  }
}

// A model change moves the request boundary, so the predicted split has to be
// recomputed — not just the episode or an explicit refresh. One watcher keeps
// an episode change that also reveals a deep-link target to a single scan;
// clearing that target after focus deliberately does not scan again.
watch(
  () => [props.projectSlug, props.episodeId, props.refreshKey, props.model, props.requestedSection] as const,
  ([projectSlug, episodeId, refreshKey, model, requested], previous) => {
    const scopeChanged = !previous
      || previous[0] !== projectSlug
      || previous[1] !== episodeId
      || previous[2] !== refreshKey
      || previous[3] !== model
    if (scopeChanged || requested?.trim()) void refresh()
  },
  { immediate: true },
)
</script>

