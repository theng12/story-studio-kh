/**
 * The episode's own TTS-model record — owner decision #8, v1.4.208
 *
 * WHAT WAS WRONG. `services/audio-reconciler.ts` predicts which
 * `{code}_{slug}_part{N}.mp3` files an episode should have, and that prediction
 * depends on the request boundary the audio was split at — which belongs to the
 * TTS model that generated it. Nothing recorded the model per episode, so when
 * an episode's own job had aged out of the queue's terminal history the
 * reconciler borrowed the PROJECT's most recent audio job instead. After a model
 * change that is another episode's model, and it predicts `_part1`/`_part2` for
 * a section the new model renders as one file: it reports parts that were never
 * supposed to exist, and says nothing about why (AGENTS.md §4).
 *
 * THE FIX. The generator writes `audio_tts_model.json` into the episode folder
 * when the generated bytes become the active selection, and the reconciler
 * resolves the boundary from it before falling back to the borrow.
 *
 * THE RED CASE. The first test below stores a small recorded budget and asserts
 * the reconciler predicts the parts that budget implies. It passes with NO API
 * key and NO catalogue reachable — because a stored budget needs no lookup. The
 * old code never opened the record, found no job history, resolved no boundary,
 * and predicted one file per section, so that assertion failed.
 */
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import test from 'node:test'

import { useTempDataDir } from './_helpers.js'

/** A chapter long enough to split into several requests at a 100-character budget. */
const CHAPTER = Array.from(
  { length: 12 },
  (_, i) => `Sentence number ${i + 1} carries enough words to occupy some room in the request.`,
).join(' ')

async function episodeFixture(name: string) {
  const tmp = await useTempDataDir()
  const pm = await import('../services/project-manager.js')
  const { resolveEpisodePathsByCode } = await import('../services/utils.js')
  const project = await pm.createProject({ name, episode_prefix: 'EP', episode_digits: 4 })
  const code = 'EP0001'
  const paths = await resolveEpisodePathsByCode(project.slug, code)
  await Promise.all([
    paths.episode_dir,
    paths.script_dir,
    paths.audio_dir,
  ].map(dir => fs.mkdir(dir, { recursive: true })))
  await fs.writeFile(
    paths.narration_docx,
    `# Narration\n\n## Chapter 01: Recorded model\n\n${CHAPTER}\n`,
  )
  return { tmp, project, code, paths }
}

test('the episode\'s own recorded model decides the split, with no job history and no catalogue', async () => {
  const { tmp, project, code, paths } = await episodeFixture('TTS record')
  try {
    const { getAudioStatus } = await import('../services/audio-reconciler.js')
    const { writeAudioTtsModelRecord } = await import('../services/audio-tts-model-record.js')

    // A boundary small enough that the chapter MUST split. Recorded, not looked
    // up: getAudioStatus is given no selected model, the project has no audio
    // job, and there is no API key — so this figure can only come from the
    // episode's own record.
    await writeAudioTtsModelRecord(paths.episode_dir, {
      schema_version: 1,
      episode_code: code,
      model_id: 'recorded-voice-model',
      model_display_name: 'Recorded Voice Model',
      published_maximum_input_characters: 120,
      request_budget: 100,
      safety_margin: 0.1,
      recorded_at: new Date().toISOString(),
    })

    const status = await getAudioStatus(project.slug, code)
    const names = status.expected.map(chunk => chunk.filename)

    assert.ok(names.length > 1, `expected the recorded budget to split the chapter; got ${JSON.stringify(names)}`)
    assert.ok(
      names.includes(`${code}_Chapter_01_part1.mp3`),
      `the reconciler must predict the parts the episode's own model produces; got ${JSON.stringify(names)}`,
    )
    assert.equal(status.expected[0]!.totalChunks, names.length)
    assert.equal(status.provider, 'genstudio', 'a recorded GenStudio model is still GenStudio work')
  } finally {
    await tmp.cleanup()
  }
})

test('with no record and no job history the section is expected whole — never an invented boundary', async () => {
  const { tmp, project, code } = await episodeFixture('TTS no record')
  try {
    const { getAudioStatus } = await import('../services/audio-reconciler.js')
    const status = await getAudioStatus(project.slug, code)
    assert.equal(status.expected.length, 1)
    assert.equal(status.expected[0]!.filename, `${code}_Chapter_01.mp3`)
  } finally {
    await tmp.cleanup()
  }
})

test('the caller\'s live selection is not overridden by the episode\'s record', async () => {
  // The Audio Generator shows the split for the model being chosen NOW, so a
  // supplied selection must win. Here the catalogue is unreachable (no API key),
  // so the honest answer is one request — pointedly NOT the recorded 100, which
  // would be the wrong question answered confidently.
  const { tmp, project, code, paths } = await episodeFixture('TTS selection wins')
  try {
    const { getAudioStatus } = await import('../services/audio-reconciler.js')
    const { writeAudioTtsModelRecord } = await import('../services/audio-tts-model-record.js')
    await writeAudioTtsModelRecord(paths.episode_dir, {
      schema_version: 1,
      episode_code: code,
      model_id: 'recorded-voice-model',
      published_maximum_input_characters: 120,
      request_budget: 100,
      safety_margin: 0.1,
      recorded_at: new Date().toISOString(),
    })
    const status = await getAudioStatus(project.slug, code, 'a-model-chosen-right-now')
    assert.equal(status.expected.length, 1)
    assert.equal(status.expected[0]!.filename, `${code}_Chapter_01.mp3`)
  } finally {
    await tmp.cleanup()
  }
})

test('a missing, corrupt, or unattributable record reads as "no record"', async () => {
  const { tmp, paths } = await episodeFixture('TTS record tolerance')
  try {
    const { readAudioTtsModelRecord, writeAudioTtsModelRecord, AUDIO_TTS_MODEL_SIDECAR } =
      await import('../services/audio-tts-model-record.js')
    const sidecar = `${paths.episode_dir}/${AUDIO_TTS_MODEL_SIDECAR}`

    assert.equal(await readAudioTtsModelRecord(paths.episode_dir), null, 'absent file is no record')

    await fs.writeFile(sidecar, '{ not json')
    assert.equal(await readAudioTtsModelRecord(paths.episode_dir), null, 'corrupt file is no record')

    await fs.writeFile(sidecar, JSON.stringify({ schema_version: 1, request_budget: 100 }))
    assert.equal(await readAudioTtsModelRecord(paths.episode_dir), null,
      'a record that names no model cannot be attributed to a boundary, so it is no record')

    // A record naming a model but carrying no usable budget still comes back —
    // its model is re-resolved against the live catalogue rather than a
    // missing figure being read as "split at zero".
    await writeAudioTtsModelRecord(paths.episode_dir, {
      schema_version: 1,
      episode_code: 'EP0001',
      model_id: 'recorded-voice-model',
      published_maximum_input_characters: 0,
      request_budget: 0,
      safety_margin: 0.1,
      recorded_at: new Date().toISOString(),
    })
    const record = await readAudioTtsModelRecord(paths.episode_dir)
    assert.equal(record?.model_id, 'recorded-voice-model')
    assert.equal(record?.request_budget, 0, 'zero means "not usable", so the caller re-resolves')
  } finally {
    await tmp.cleanup()
  }
})
