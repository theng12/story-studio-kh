/**
 * Per-scene animation filter builders — now a thin adapter over the
 * declarative registry.
 *
 * v1.2.0 moved every animation out of the switch that used to live here and
 * into `contracts/scene-effect-presets.ts` as data, compiled by
 * `lib/scene-effect-compiler.ts`. Nothing about the emitted FFmpeg changed:
 * `__tests__/scene-effect-registry.test.ts` compares 965 filter strings
 * captured from the v1.1.0 tree, byte for byte, across every animation and
 * every parameter range.
 *
 * What remains here is the legacy CALL SHAPE — `{ type, params, w, h, fps,
 * duration }`, where `params` is the flat `VideoSceneAnimation` every project
 * on disk holds. Resolving a name to a document and folding those flat params
 * into it is all this file now does.
 *
 * `normalizeFrame` stays because it is not an animation: it is the frame shape
 * EVERY clip flowing into the final concat must have, animated or not.
 */

import { compileSceneMotion } from './scene-effect-compiler.js'
import {
  BUILT_IN_SCENE_MOTIONS,
  DEFAULT_SCENE_MOTION_ID,
  MissingPackEffectError,
  type BuiltInMotion,
} from '../contracts/scene-effect-presets.js'
import { applyLegacyMotionParams } from '../contracts/scene-effects.js'
import { isContentPackItemId } from '../contracts/content-origin.js'
import type { VideoSceneAnimation } from '../models/types.js'

export interface AnimationFilterOpts {
  type: string
  params: VideoSceneAnimation
  w: number
  h: number
  fps: number
  duration: number
  /**
   * The scene-motion registry `type` is resolved against.
   *
   * v1.2.1. Defaults to the built-ins, so every existing caller and the whole
   * zero-packs case behave exactly as in v1.2.0. Video Assembly passes the
   * merged built-in + installed-pack library from
   * `services/style-effect-loader.ts`.
   */
  library?: readonly BuiltInMotion[]
}

/**
 * Standard frame normalisation chain: scale to fit, pad with black, force SAR
 * to 1, pin the output fps, normalise to yuv420p. Every clip that flows into
 * the final concat — scene, intro, post-audio filler — must emit this shape
 * so xfade and concat can stitch them without size/SAR mismatches.
 *
 * Returned as an array because FFmpeg filter chains join tokens with `,`.
 * Hand-writing the equivalent string is how the post_fade.mp4 bug happened
 * on FFmpeg 8.1 — a stray `:setsar=1` looks like a `pad` option. Use this
 * helper; never concatenate `pad` + `setsar` by hand again.
 */
export function normalizeFrame(w: number, h: number, fps: number): string[] {
  // `setsar` intentionally comes BEFORE `pad`. FFmpeg 8.1 mis-parses
  // `pad=...:color=black,setsar=1` as if `setsar` were a pad option,
  // which blew up post_fade.mp4 renders on long episodes. Putting setsar
  // upstream sidesteps the adjacency without changing the output frame.
  return [
    `scale=${w}:${h}:force_original_aspect_ratio=decrease`,
    'setsar=1',
    `pad=${w}:${h}:(ow-iw)/2:(oh-ih)/2:color=black`,
    `fps=${fps}`,
    'format=yuv420p',
  ]
}

/** Pick a supersampling multiplier that balances quality vs memory cost.
 *  v1.0.515 — was 4× at ≤1080p, which upscaled every source to 7680×4320
 *  (33 MP) before zoompan. zoompan is single-threaded and its per-frame cost
 *  scales with canvas area, so 4× cost ~4× the wall-clock of 2× for no
 *  visible gain (sources are typically 1–2 MP — there's no extra detail to
 *  sample past ~2×). 2× (3840×2160 at 1080p) is the standard anti-jitter
 *  level and renders scenes in seconds instead of minutes. */
export function supersampleMultiplier(_w: number, _h: number): number {
  return 2
}

function missingPackMotion(type: string): never {
  throw new MissingPackEffectError(
    `A scene uses the camera move "${type}", which comes from a Content Pack that is not installed. `
    + 'Rendering now would publish the scene with no motion at all. Reinstall the pack from the Content Store, '
    + 'or choose another animation for that scene, then run this job again — no completed work is repeated.',
    [type],
  )
}

function usesZoompan(motion: BuiltInMotion): boolean {
  return motion.document.spin.rate_rad_per_sec === 0
    && (motion.document.zoom.mode !== 'none' || motion.document.pan.mode !== 'none')
}

const ZOOMPAN_TYPES = new Set(BUILT_IN_SCENE_MOTIONS.filter(usesZoompan).map(m => m.id))

/**
 * Animations whose clip is generated by `zoompan`.
 *
 * DERIVED from the registry rather than listed: an animation is a zoompan
 * animation exactly when its document declares a virtual camera. The old
 * hand-kept `Set` of eighteen names could drift from the switch beside it; this
 * cannot.
 *
 * Callers need this because `zoompan` builds the ENTIRE clip from ONE input
 * frame (`d` frames per input frame), so feeding the image with `-loop 1 -t D`
 * made FFmpeg decode and supersample-upscale the same PNG ~25xD times for
 * frames zoompan never consumed — about 90% of scene-prep time (v1.0.515).
 *
 * `library` (v1.2.1) lets a caller ask the question of the merged built-in +
 * installed-pack registry. Omitted, it answers from the built-ins alone, which
 * is what every pre-pack caller means.
 */
export function isZoompanAnimation(type: string, library?: readonly BuiltInMotion[]): boolean {
  if (!library) return ZOOMPAN_TYPES.has(type)
  const entry = library.find(motion => motion.id === type)
  return !!entry && usesZoompan(entry)
}

/**
 * Entry point.
 *
 * An unrecognised BARE name falls back to the static motion rather than
 * throwing — a project naming an animation this build does not have still
 * renders, it just renders still. That has been true since v1.0 and stays true.
 *
 * A qualified name is different, and v1.2.1 separates the two. A reverse-DNS id
 * can only be in a project because a Content Pack put it there, so failing to
 * resolve one means the pack has been uninstalled, disabled or recalled.
 * Rendering the scene motionless would hand the customer a finished video whose
 * camera work quietly vanished, so it refuses instead and says how to repair it.
 */
export function buildAnimationFilter(opts: AnimationFilterOpts): string[] {
  const library = opts.library ?? BUILT_IN_SCENE_MOTIONS
  const entry = library.find(motion => motion.id === opts.type)
    ?? (isContentPackItemId(opts.type) ? missingPackMotion(opts.type) : undefined)
    ?? library.find(motion => motion.id === DEFAULT_SCENE_MOTION_ID)
    ?? BUILT_IN_SCENE_MOTIONS.find(motion => motion.id === DEFAULT_SCENE_MOTION_ID)!
  const document = applyLegacyMotionParams(entry.document, entry.legacy_binding, opts.params)
  return compileSceneMotion(document, {
    w: opts.w, h: opts.h, fps: opts.fps, duration: opts.duration,
  })
}
